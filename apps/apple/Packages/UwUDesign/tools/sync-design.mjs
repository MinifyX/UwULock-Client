#!/usr/bin/env node
// Brings @uwusuite/design into the native app's design package (UwUDesign). The package stays
// the source of truth (docs/design.md): this only translates it, it never invents values.
//
//   node apps/apple/Packages/UwUDesign/tools/sync-design.mjs
//
// Needs `pnpm install` (it reads the package the desktop app has, apps/desktop/node_modules).
// Writes, all under Sources/UwUDesign:
//   Resources/Colors.xcassets   every colour token of tokens.css: light, dark, increased contrast
//                               (light and dark), as the CSS cascade resolves them
//   Resources/Icons.xcassets    the Lucide/suite icons of ICONS the desktop UI uses (template SVGs)
//   Resources/Nyu.xcassets      Nyu as a padlock in every mood, the sticker edge baked in
//   Resources/Fonts             UwU Sans, JetBrains Mono and the picker's fonts (WOFF2, CoreText
//                               reads them), with their licences
//   Generated/*.swift           the Swift names for all of that
// Run it again after bumping @uwusuite/design in apps/desktop/package.json and commit the result.

import { createRequire } from 'node:module';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(here, '..');
const repo = join(pkgRoot, '..', '..', '..', '..');
const desktop = join(repo, 'apps', 'desktop');
const sources = join(pkgRoot, 'Sources', 'UwUDesign');
const resources = join(sources, 'Resources');
const generated = join(sources, 'Generated');

const require = createRequire(join(desktop, 'package.json'));
const load = (spec) => import(pathToFileURL(require.resolve(spec)).href);
const designDir = join(dirname(require.resolve('@uwusuite/design/package.json')));
const designRequire = createRequire(join(designDir, 'package.json'));
const designVersion = JSON.parse(readFileSync(join(designDir, 'package.json'), 'utf8')).version;

const HEADER = `// Generated by tools/sync-design.mjs from @uwusuite/design ${designVersion}. Don't edit.\n`;
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const INFO = { author: 'xcode', version: 1 };

function fresh(dir) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'Contents.json'), json({ info: INFO }));
}

const SWIFT_KEYWORDS = new Set(['import', 'repeat', 'default', 'case', 'return', 'in', 'is', 'as', 'func', 'let', 'var', 'class', 'struct', 'enum', 'protocol', 'extension', 'switch', 'for', 'while', 'if', 'else', 'do', 'try', 'throw', 'self', 'super', 'init', 'deinit', 'operator', 'where', 'break', 'continue', 'guard', 'defer', 'static', 'public', 'private', 'internal', 'fileprivate', 'true', 'false', 'nil', 'subscript', 'typealias', 'associatedtype', 'inout', 'any', 'some']);
const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (name) => camel(name).replace(/^./, (c) => c.toUpperCase());

mkdirSync(generated, { recursive: true });

// ---------------------------------------------------------------------------------------------
// Colours

const css = readFileSync(join(designDir, 'dist', 'css', 'tokens.css'), 'utf8').replace(
  /\/\*[\s\S]*?\*\//g,
  '',
);

function block(selector) {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`tokens.css has no "${selector}" block`);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const out = {};
  for (const [, name, value] of body.matchAll(/--uwu-([a-z0-9-]+):\s*([^;]+);/g)) out[name] = value.trim();
  return out;
}

function parseColor(value) {
  let m = value.match(/^#([0-9a-f]{6})$/i);
  if (m) {
    const n = parseInt(m[1], 16);
    return { r: n >> 16, g: (n >> 8) & 255, b: n & 255, a: 1 };
  }
  m = value.match(/^rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*(?:\/\s*([\d.]+))?\s*\)$/);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] === undefined ? 1 : +m[4] };
  return null;
}

// The cascade of tokens.css: high contrast (html:root[…]) outranks the dark theme.
const root = block(':root');
const dark = { ...root, ...block(':root[data-theme="dark"]') };
const hcLight = { ...root, ...block('html:root[data-contrast="high"]') };
const hcDark = {
  ...dark,
  ...block('html:root[data-contrast="high"]'),
  ...block('html:root[data-contrast="high"][data-theme="dark"]'),
};

const colorsDir = join(resources, 'Colors.xcassets');
fresh(colorsDir);
const colorNames = [];
for (const name of Object.keys(root)) {
  const variants = [root, dark, hcLight, hcDark].map((set) => parseColor(set[name] ?? ''));
  if (variants.some((v) => !v)) continue; // not a colour (sizes, shadows, fonts, …)
  const hex = (n) => `0x${n.toString(16).padStart(2, '0').toUpperCase()}`;
  const entry = (c, appearances) => ({
    idiom: 'universal',
    ...(appearances.length ? { appearances } : {}),
    color: {
      'color-space': 'srgb',
      components: { red: hex(c.r), green: hex(c.g), blue: hex(c.b), alpha: c.a.toFixed(3) },
    },
  });
  const luminosity = (value) => ({ appearance: 'luminosity', value });
  const contrast = { appearance: 'contrast', value: 'high' };
  const set = join(colorsDir, `${name}.colorset`);
  mkdirSync(set);
  writeFileSync(
    join(set, 'Contents.json'),
    json({
      colors: [
        entry(variants[0], []),
        entry(variants[1], [luminosity('dark')]),
        entry(variants[2], [contrast]),
        entry(variants[3], [luminosity('dark'), contrast]),
      ],
      info: INFO,
    }),
  );
  colorNames.push(name);
}

writeFileSync(
  join(generated, 'Colors.swift'),
  `${HEADER}
import SwiftUI

/// Every colour token of the suite (tokens.css), light, dark and increased contrast, from the
/// asset catalog. Use them as \`.foregroundStyle(.uwuInk)\`, \`Color.uwuPinkSolid\` and so on.
/// Rules (package docs/color.md): text on a pink fill uses \`uwuPinkSolid\`, a state's text its
/// \`-Ink\` token; pink means selected or focus, never "ok".
extension ShapeStyle where Self == Color {
${colorNames
  .map((n) => `    /// \`--uwu-${n}\`\n    public static var uwu${pascal(n)}: Color { Color("${n}", bundle: .module) }`)
  .join('\n')}
}

/// The names of all colour tokens, for previews and tests.
public enum UwUColorToken: String, CaseIterable, Sendable {
${colorNames.map((n) => `    case ${camel(n)} = "${n}"`).join('\n')}

    public var color: Color { Color(rawValue, bundle: .module) }
}
`,
);

// ---------------------------------------------------------------------------------------------
// Icons: what the desktop UI uses (ICONS.<name> in apps/desktop/src), plus the native shell's own.

const SHELL_ICONS = ['add', 'more', 'settings', 'search', 'locked', 'unlocked', 'favorite', 'delete'];

function walk(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path, out);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) out.push(path);
  }
  return out;
}
const used = new Set(SHELL_ICONS);
for (const file of walk(join(desktop, 'src')))
  for (const [, name] of readFileSync(file, 'utf8').matchAll(/ICONS\.([A-Za-z0-9_]+)/g)) used.add(name);

const { ICONS, ICON_SIZES } = await load('@uwusuite/design');
const { createElement } = await load('react');
const { renderToStaticMarkup } = await load('react-dom/server');

// One SVG per icon, drawn at 24 pt with the stroke of the md size (18 px · 1.8 → 2.4 on the
// 24 grid): the native app shows icons at 17–22 pt, where that matches the desktop's look.
const STROKE = Math.round(((ICON_SIZES.md.stroke * 24) / ICON_SIZES.md.px) * 100) / 100;
const iconsDir = join(resources, 'Icons.xcassets');
fresh(iconsDir);
// Asset names: "icon-" keeps Xcode's generated asset symbols apart from colours and Nyu, and a
// trailing "Image" gets a suffix (Xcode drops it, so addImage would clash with add).
const iconAsset = (name) => `icon-${name}${name.endsWith('Image') ? 'Glyph' : ''}`;
const iconNames = [...used].filter((n) => ICONS[n]).sort();
for (const missing of [...used].filter((n) => !ICONS[n])) console.warn(`! ICONS.${missing} doesn't exist`);
for (const name of iconNames) {
  let svg = renderToStaticMarkup(createElement(ICONS[name], { size: 24, strokeWidth: STROKE }));
  // CoreSVG knows no currentColor; a template image takes its colour from the tint anyway.
  svg = svg.replaceAll('currentColor', '#000000').replace(/ class="[^"]*"/, '').replace(/ aria-hidden="true"/, '');
  const set = join(iconsDir, `${iconAsset(name)}.imageset`);
  mkdirSync(set);
  writeFileSync(join(set, `${name}.svg`), svg);
  writeFileSync(
    join(set, 'Contents.json'),
    json({
      images: [{ filename: `${name}.svg`, idiom: 'universal' }],
      info: INFO,
      properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' },
    }),
  );
}

writeFileSync(
  join(generated, 'IconNames.swift'),
  `${HEADER}
/// The suite's icon vocabulary (package docs/icons.md: one meaning, one icon), limited to what
/// UwULock uses. The raw value is the meaning's name in \`ICONS\`.
public enum UwUIconName: String, CaseIterable, Sendable {
${iconNames.map((n) => `    case ${SWIFT_KEYWORDS.has(n) ? `\`${n}\`` : n}`).join('\n')}

    /// The image's name in the package's asset catalog.
    var assetName: String {
        switch self {
${iconNames
  .filter((n) => iconAsset(n) !== `icon-${n}`)
  .map((n) => `        case .${n}: "${iconAsset(n)}"`)
  .join('\n')}
        default: "icon-\\(rawValue)"
        }
    }
}
`,
);

// ---------------------------------------------------------------------------------------------
// Nyu: the padlock cat (shell "lock") in every mood. nyu.css paints the sticker's edge white;
// SVG in an asset catalog has no CSS, so the edge's colours are written into the markup.

const { nyuSvg, MOODS } = await load('@uwusuite/design/nyu-svg');

function bakeEdge(svg) {
  const open = svg.indexOf('<g class="nyu-edge"');
  if (open < 0) return svg;
  const headEnd = svg.indexOf('>', open) + 1;
  // sticker() writes the inner markup twice: inside the edge group, then as it is.
  let close = headEnd;
  let inner = null;
  while ((close = svg.indexOf('</g>', close)) >= 0) {
    const candidate = svg.slice(headEnd, close);
    if (svg.startsWith(candidate, close + 4)) {
      inner = candidate;
      break;
    }
    close += 4;
  }
  if (inner === null) throw new Error('Nyu: the sticker edge has an unexpected shape');
  const width = svg.slice(open, headEnd).match(/stroke-width="([\d.]+)"/)[1];

  // Walk the tags: drop .no-edge elements, paint the rest white, one stroke width for all.
  let out = '';
  let skip = 0;
  let noneDepth = 0;
  const stack = [];
  for (const [tag] of inner.matchAll(/<[^>]+>/g)) {
    const closing = tag.startsWith('</');
    const selfClosing = tag.endsWith('/>');
    if (closing) {
      const top = stack.pop();
      if (top?.skipped) skip--;
      else if (!skip) out += tag;
      if (top?.none) noneDepth--;
      continue;
    }
    const noEdge = /class="[^"]*\bno-edge\b/.test(tag);
    if (skip || noEdge) {
      if (!selfClosing) {
        stack.push({ skipped: true });
        skip++;
      }
      continue;
    }
    const none = /fill="none"/.test(tag) || noneDepth > 0;
    let t = tag
      .replace(/ stroke-width="[^"]*"/g, '')
      .replace(/ stroke="[^"]*"/g, ' stroke="#FFFFFF"')
      .replace(/ fill="[^"]*"/g, none ? ' fill="none"' : ' fill="#FFFFFF"')
      .replace(/ opacity="[^"]*"/g, '');
    if (!/ stroke=/.test(t)) t = t.replace(/^<(\w+)/, '<$1 stroke="#FFFFFF"');
    out += t;
    if (!selfClosing) {
      stack.push({ none: /fill="none"/.test(tag) });
      if (/fill="none"/.test(tag)) noneDepth++;
    }
  }
  const edge = `<g fill="#FFFFFF" stroke="#FFFFFF" stroke-width="${width}">${out}</g>`;
  return svg.slice(0, open) + edge + svg.slice(close + 4);
}

const nyuDir = join(resources, 'Nyu.xcassets');
fresh(nyuDir);
for (const mood of MOODS) {
  let svg = nyuSvg({ shell: 'lock', mood, label: '', blink: false });
  svg = bakeEdge(svg)
    .replace(/<svg [^>]*?viewBox="([^"]+)"[^>]*>/, (_, vb) => {
      const [, , w, h] = vb.split(/\s+/).map(Number);
      return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${w}" height="${h}">`;
    })
    .replace(/ class="[^"]*"/g, '');
  const name = `nyu-lock-${mood}`;
  const set = join(nyuDir, `${name}.imageset`);
  mkdirSync(set);
  writeFileSync(join(set, `${name}.svg`), svg);
  writeFileSync(
    join(set, 'Contents.json'),
    json({
      images: [{ filename: `${name}.svg`, idiom: 'universal' }],
      info: INFO,
      properties: { 'preserves-vector-representation': true },
    }),
  );
}

writeFileSync(
  join(generated, 'NyuMoods.swift'),
  `${HEADER}
/// Nyu's moods (package docs/nyu.md). UwULock's Nyu is the padlock cat.
public enum NyuMood: String, CaseIterable, Sendable {
${MOODS.map((m) => `    case ${m}`).join('\n')}
}
`,
);

// ---------------------------------------------------------------------------------------------
// Fonts: UwU Sans from the package, the others from @fontsource-variable (their Latin subset,
// which covers German and English). CoreText reads WOFF2 directly.

const fontsDir = join(resources, 'Fonts');
rmSync(fontsDir, { recursive: true, force: true });
mkdirSync(fontsDir, { recursive: true });
copyFileSync(join(designDir, 'fonts', 'UwUSans[wght].woff2'), join(fontsDir, 'UwUSans.woff2'));
copyFileSync(join(designDir, 'fonts', 'OFL.txt'), join(fontsDir, 'UwUSans-OFL.txt'));
for (const [pkg, file] of [
  ['jetbrains-mono', 'JetBrainsMono'],
  ['manrope', 'Manrope'],
  ['rubik', 'Rubik'],
  ['dm-sans', 'DMSans'],
]) {
  // The picker's fonts come with @uwusuite/design (its dependencies, not the desktop app's).
  const licence = designRequire.resolve(`@fontsource-variable/${pkg}/LICENSE`);
  const dir = dirname(licence);
  copyFileSync(join(dir, 'files', `${pkg}-latin-wght-normal.woff2`), join(fontsDir, `${file}.woff2`));
  copyFileSync(licence, join(fontsDir, `${file}-LICENSE.txt`));
}

console.log(
  `UwUDesign synced from @uwusuite/design ${designVersion}: ${colorNames.length} colours, ` +
    `${iconNames.length} icons, ${MOODS.length} Nyu moods, fonts.`,
);
